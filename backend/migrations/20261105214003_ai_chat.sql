-- Create "ai_settings" table
CREATE TABLE "public"."ai_settings" (
  "id" integer NOT NULL,
  "enabled" boolean NOT NULL,
  "base_url" character varying(255) NOT NULL,
  "model" character varying(160) NOT NULL,
  "api_key" text NOT NULL,
  "temperature" double precision NOT NULL,
  "max_steps" integer NOT NULL,
  "daily_limit" integer NOT NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "pk_ai_settings" PRIMARY KEY ("id")
);
-- Create "chats" table
CREATE TABLE "public"."chats" (
  "id" uuid NOT NULL,
  "user_id" uuid NOT NULL,
  "title" character varying(160) NOT NULL,
  "status" character varying(16) NOT NULL,
  "tokens" bigint NOT NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "pk_chats" PRIMARY KEY ("id"),
  CONSTRAINT "fk_chats_user_id_users" FOREIGN KEY ("user_id") REFERENCES "public"."users" ("id") ON UPDATE NO ACTION ON DELETE CASCADE
);
-- Create index "ix_chats_user_updated" to table: "chats"
CREATE INDEX "ix_chats_user_updated" ON "public"."chats" ("user_id", "updated_at");
-- Create "chat_actions" table
CREATE TABLE "public"."chat_actions" (
  "id" uuid NOT NULL,
  "chat_id" uuid NOT NULL,
  "tool" character varying(64) NOT NULL,
  "args" jsonb NOT NULL,
  "summary" character varying(400) NOT NULL,
  "status" character varying(16) NOT NULL,
  "result" jsonb NOT NULL,
  "undo" jsonb NOT NULL,
  "created_at" timestamptz NOT NULL,
  "done_at" timestamptz NULL,
  CONSTRAINT "pk_chat_actions" PRIMARY KEY ("id"),
  CONSTRAINT "fk_chat_actions_chat_id_chats" FOREIGN KEY ("chat_id") REFERENCES "public"."chats" ("id") ON UPDATE NO ACTION ON DELETE CASCADE
);
-- Create index "ix_chat_actions_chat_id" to table: "chat_actions"
CREATE INDEX "ix_chat_actions_chat_id" ON "public"."chat_actions" ("chat_id");
-- Create "chat_messages" table
CREATE TABLE "public"."chat_messages" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "chat_id" uuid NOT NULL,
  "role" character varying(16) NOT NULL,
  "content" text NOT NULL,
  "data" jsonb NOT NULL,
  "created_at" timestamptz NOT NULL,
  CONSTRAINT "pk_chat_messages" PRIMARY KEY ("id"),
  CONSTRAINT "fk_chat_messages_chat_id_chats" FOREIGN KEY ("chat_id") REFERENCES "public"."chats" ("id") ON UPDATE NO ACTION ON DELETE CASCADE
);
-- Create index "ix_chat_messages_chat" to table: "chat_messages"
CREATE INDEX "ix_chat_messages_chat" ON "public"."chat_messages" ("chat_id", "id");
