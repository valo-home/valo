-- Create "cameras" table
CREATE TABLE "public"."cameras" (
  "id" character varying(64) NOT NULL,
  "device_id" character varying(128) NOT NULL,
  "driver" character varying(128) NOT NULL,
  "config" jsonb NOT NULL,
  "streams" jsonb NOT NULL,
  "info" jsonb NOT NULL,
  "record" jsonb NOT NULL,
  "sort" integer NOT NULL,
  "created_at" timestamptz NOT NULL,
  "updated_at" timestamptz NOT NULL,
  CONSTRAINT "pk_cameras" PRIMARY KEY ("id"),
  CONSTRAINT "uq_cameras_device_id" UNIQUE ("device_id"),
  CONSTRAINT "fk_cameras_device_id_devices" FOREIGN KEY ("device_id") REFERENCES "public"."devices" ("id") ON UPDATE NO ACTION ON DELETE CASCADE
);
-- Create index "ix_cameras_driver" to table: "cameras"
CREATE INDEX "ix_cameras_driver" ON "public"."cameras" ("driver");
-- Create "media" table
CREATE TABLE "public"."media" (
  "id" uuid NOT NULL,
  "camera_id" character varying(64) NULL,
  "event_id" bigint NULL,
  "kind" character varying(8) NOT NULL,
  "path" character varying(512) NOT NULL,
  "size" bigint NOT NULL,
  "duration" double precision NULL,
  "origin" character varying(160) NOT NULL,
  "meta" jsonb NOT NULL,
  "created_at" timestamptz NOT NULL,
  CONSTRAINT "pk_media" PRIMARY KEY ("id"),
  CONSTRAINT "fk_media_camera_id_cameras" FOREIGN KEY ("camera_id") REFERENCES "public"."cameras" ("id") ON UPDATE NO ACTION ON DELETE SET NULL
);
-- Create index "ix_media_camera_ts" to table: "media"
CREATE INDEX "ix_media_camera_ts" ON "public"."media" ("camera_id", "created_at");
-- Create index "ix_media_created_at" to table: "media"
CREATE INDEX "ix_media_created_at" ON "public"."media" ("created_at");
-- Create index "ix_media_event_id" to table: "media"
CREATE INDEX "ix_media_event_id" ON "public"."media" ("event_id");
-- Create "camera_events" table
CREATE TABLE "public"."camera_events" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "camera_id" character varying(64) NOT NULL,
  "label" character varying(32) NOT NULL,
  "source" character varying(160) NOT NULL,
  "score" double precision NULL,
  "data" jsonb NOT NULL,
  "started_at" timestamptz NOT NULL,
  "ended_at" timestamptz NULL,
  "snapshot_id" uuid NULL,
  "clip_id" uuid NULL,
  CONSTRAINT "pk_camera_events" PRIMARY KEY ("id"),
  CONSTRAINT "fk_camera_events_camera_id_cameras" FOREIGN KEY ("camera_id") REFERENCES "public"."cameras" ("id") ON UPDATE NO ACTION ON DELETE CASCADE,
  CONSTRAINT "fk_camera_events_clip_id_media" FOREIGN KEY ("clip_id") REFERENCES "public"."media" ("id") ON UPDATE NO ACTION ON DELETE SET NULL,
  CONSTRAINT "fk_camera_events_snapshot_id_media" FOREIGN KEY ("snapshot_id") REFERENCES "public"."media" ("id") ON UPDATE NO ACTION ON DELETE SET NULL
);
-- Create index "ix_camera_events_camera_ts" to table: "camera_events"
CREATE INDEX "ix_camera_events_camera_ts" ON "public"."camera_events" ("camera_id", "started_at");
